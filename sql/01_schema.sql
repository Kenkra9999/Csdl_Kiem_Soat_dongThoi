-- =====================================================================
-- ĐỀ TÀI 19 - 01_schema.sql: BẢNG, KHÓA, RÀNG BUỘC, CHỈ MỤC, TRIGGER
-- Chạy trong CSDL riêng của đồ án; không xóa CSDL/schema có sẵn.
-- CSDL đã cài bản cũ: chạy 07_nang_cap.sql (không cần cài lại).
--
-- Mục lục
--   1. Người dùng, danh mục, tài sản và 3 lớp con (chuyên biệt hóa EER)
--   2. Phiên đấu giá, đăng ký, lượt trả giá, kết quả, nhật ký
--   3. Chỉ mục
--   4. Trigger: cây danh mục không chu trình
--   5. Trigger: tài sản thuộc ĐÚNG MỘT lớp con (total + disjoint)
--   6. Trigger: lịch sử/kết quả/nhật ký không được sửa, xóa
--   7. Trigger: giá hiện tại (cache) và kết quả khớp lịch sử trả giá
-- =====================================================================
BEGIN;
CREATE SCHEMA IF NOT EXISTS auction;

-- ---------------------------------------------------------------------
-- 1. NGƯỜI DÙNG, DANH MỤC, TÀI SẢN
-- ---------------------------------------------------------------------
-- Không có cột "vai trò": người bán = assets.seller_id, người tham gia =
-- registrations. Một người có thể bán phiên A và trả giá phiên B.
CREATE TABLE IF NOT EXISTS auction.users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  text NOT NULL CHECK (btrim(full_name) <> ''),
    email      text NOT NULL UNIQUE                     -- khóa ứng viên thứ 2
               CHECK (email = lower(email) AND position('@' IN email) > 1),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Cây danh mục: tối đa một cha; tên chỉ duy nhất trong cùng một cha.
CREATE TABLE IF NOT EXISTS auction.categories (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES auction.categories(id),
    name      text NOT NULL CHECK (btrim(name) <> ''),
    CHECK (parent_id IS DISTINCT FROM id),                 -- không tự làm cha
    UNIQUE NULLS NOT DISTINCT (parent_id, name)            -- NULL (gốc) coi như bằng nhau
);

-- Lớp cha TaiSan. kind là thuộc tính phân loại của chuyên biệt hóa.
CREATE TABLE IF NOT EXISTS auction.assets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id   bigint NOT NULL REFERENCES auction.users(id),
    category_id bigint NOT NULL REFERENCES auction.categories(id),
    kind        text NOT NULL CHECK (kind IN ('ARTWORK', 'COLLECTIBLE', 'ELECTRONIC')),
    title       text NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL DEFAULT '',
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Ba lớp con: asset_id vừa là PK vừa là FK tới lớp cha (quan hệ 1:1).
CREATE TABLE IF NOT EXISTS auction.artworks (
    asset_id      bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    artist        text NOT NULL,
    material      text NOT NULL,
    creation_year integer CHECK (creation_year BETWEEN 1 AND 9999)
);
CREATE TABLE IF NOT EXISTS auction.collectibles (
    asset_id        bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    origin          text NOT NULL,
    rarity          text NOT NULL,
    production_year integer CHECK (production_year BETWEEN 1 AND 9999)
);
CREATE TABLE IF NOT EXISTS auction.electronics (
    asset_id      bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    brand         text NOT NULL,
    model         text NOT NULL,
    serial_number text UNIQUE,                             -- duy nhất khi có giá trị
    condition     text NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. PHIÊN, ĐĂNG KÝ, LƯỢT TRẢ GIÁ, KẾT QUẢ, NHẬT KÝ
-- ---------------------------------------------------------------------
-- Ba loại giá được tách bạch:
--   start_price   : giá khởi điểm (cấu hình phiên)
--   bids.amount   : giá của từng lượt trả
--   current_price : CACHE = MAX(bids.amount) của phiên, NULL khi chưa có lượt
--   giá thắng     : không lưu riêng, = bids.amount của results.winning_bid_id
-- revision tăng ở mỗi lần ghi phiên; lệnh UPDATE này là "điểm giành quyền
-- ghi" trong place_bid/close_auction (xem 02_functions.sql).
CREATE TABLE IF NOT EXISTS auction.auctions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id       bigint NOT NULL REFERENCES auction.assets(id),
    start_price    numeric(18,2) NOT NULL CHECK (start_price > 0 AND start_price <> 'NaN'::numeric),
    bid_step       numeric(18,2) NOT NULL CHECK (bid_step > 0 AND bid_step <> 'NaN'::numeric),
    opens_at       timestamptz NOT NULL,
    closes_at      timestamptz NOT NULL,
    status         text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    current_price  numeric(18,2),
    leading_bid_id bigint,                                 -- FK kép thêm ở dưới
    revision       bigint NOT NULL DEFAULT 0,
    CHECK (closes_at > opens_at),
    CHECK ((current_price IS NULL) = (leading_bid_id IS NULL)),
    CHECK (current_price IS NULL OR (current_price >= start_price AND current_price <> 'NaN'::numeric))
);

-- Bảng của mối kết hợp n:m NguoiDung - PhienDauGia.
CREATE TABLE IF NOT EXISTS auction.registrations (
    auction_id    bigint NOT NULL REFERENCES auction.auctions(id),
    user_id       bigint NOT NULL REFERENCES auction.users(id),
    status        text NOT NULL DEFAULT 'APPROVED' CHECK (status IN ('APPROVED', 'REVOKED')),
    registered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (auction_id, user_id)
);

-- Lịch sử các lượt ĐÃ CHẤP NHẬN. Ba khóa ứng viên: id, request_id,
-- (auction_id, amount). Hai khóa sau là hàng rào cuối cùng ở mức CSDL:
--   * request_id  : gửi lại cùng yêu cầu không thể tạo lượt thứ hai;
--   * (auction_id, amount): hai yêu cầu cùng mức giá chỉ một được ghi.
CREATE TABLE IF NOT EXISTS auction.bids (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id  bigint NOT NULL,
    bidder_id   bigint NOT NULL,
    amount      numeric(18,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    request_id  uuid NOT NULL UNIQUE,
    accepted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    -- Người trả giá phải có dòng đăng ký ở ĐÚNG phiên này.
    FOREIGN KEY (auction_id, bidder_id) REFERENCES auction.registrations(auction_id, user_id),
    -- Siêu khóa phụ để FK kép từ auctions/results chứng minh "lượt thuộc đúng phiên".
    UNIQUE (id, auction_id),
    CONSTRAINT bids_auction_id_amount_key UNIQUE (auction_id, amount)
);

-- Lượt dẫn đầu phải thuộc đúng phiên: FK kép (leading_bid_id, id).
-- DEFERRABLE vì place_bid ghi bid rồi mới cập nhật phiên trong cùng giao dịch.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'auctions_leading_bid_fk'
                     AND conrelid = 'auction.auctions'::regclass) THEN
        ALTER TABLE auction.auctions ADD CONSTRAINT auctions_leading_bid_fk
            FOREIGN KEY (leading_bid_id, id) REFERENCES auction.bids(id, auction_id)
            DEFERRABLE INITIALLY DEFERRED;
    END IF;
END $$;

-- PK = auction_id  =>  mỗi phiên có TỐI ĐA một kết quả.
-- winning_bid_id NULL = phiên đóng không có lượt hợp lệ.
CREATE TABLE IF NOT EXISTS auction.results (
    auction_id     bigint PRIMARY KEY REFERENCES auction.auctions(id),
    winning_bid_id bigint,
    closed_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (winning_bid_id, auction_id) REFERENCES auction.bids(id, auction_id)
);

CREATE TABLE IF NOT EXISTS auction.audit_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id     bigint NOT NULL REFERENCES auction.auctions(id),
    action         text NOT NULL CHECK (action IN ('BID_ACCEPTED', 'AUCTION_CLOSED')),
    actor_id       bigint REFERENCES auction.users(id),   -- NULL khi hệ thống tự làm
    details        jsonb NOT NULL,
    occurred_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    -- Mã giao dịch PostgreSQL ghi sự kiện (pg_current_xact_id thay txid_current đã lỗi thời).
    transaction_id bigint NOT NULL DEFAULT (pg_current_xact_id()::text)::bigint
);

-- ---------------------------------------------------------------------
-- 3. CHỈ MỤC
-- ---------------------------------------------------------------------
-- Ràng buộc nghiệp vụ: một tài sản không được nằm trong HAI phiên đang mở.
-- (Tài sản vẫn có thể có nhiều phiên theo thời gian, ví dụ đấu giá lại.)
CREATE UNIQUE INDEX IF NOT EXISTS auctions_one_open_per_asset
    ON auction.auctions(asset_id) WHERE status = 'OPEN';
CREATE INDEX IF NOT EXISTS auctions_open_deadline_idx
    ON auction.auctions(closes_at) WHERE status = 'OPEN';  -- phiên sắp kết thúc
CREATE INDEX IF NOT EXISTS assets_category_idx  ON auction.assets(category_id);
CREATE INDEX IF NOT EXISTS categories_parent_idx ON auction.categories(parent_id);
CREATE INDEX IF NOT EXISTS bids_bidder_idx       ON auction.bids(bidder_id);
CREATE INDEX IF NOT EXISTS audit_auction_idx     ON auction.audit_log(auction_id, occurred_at);
-- Tìm lượt cao nhất của phiên dùng chỉ mục của bids_auction_id_amount_key.

-- ---------------------------------------------------------------------
-- 4. CÂY DANH MỤC KHÔNG CÓ CHU TRÌNH
-- ---------------------------------------------------------------------
-- Hai quản trị viên sửa đồng thời có thể cùng tạo chu trình (write skew),
-- nên mọi thao tác sửa cây xếp hàng qua một advisory lock rồi mới kiểm tra.
-- REPEATABLE READ bị từ chối: snapshot chụp TRƯỚC lúc chờ khóa nên có thể cũ.
CREATE OR REPLACE FUNCTION auction.guard_category_tree() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, auction, pg_temp AS $$
BEGIN
    IF current_setting('transaction_isolation') = 'repeatable read' THEN
        RAISE EXCEPTION 'Sửa cây danh mục dùng READ COMMITTED hoặc SERIALIZABLE có retry'
            USING ERRCODE = '25001';
    END IF;
    PERFORM pg_advisory_xact_lock(190019, 1);

    -- Đi ngược từ cha mới lên gốc; nếu gặp chính NEW.id thì có chu trình.
    IF NEW.parent_id IS NOT NULL AND EXISTS (
        WITH RECURSIVE ancestors(id, parent_id) AS (
            SELECT id, parent_id FROM auction.categories WHERE id = NEW.parent_id
            UNION
            SELECT c.id, c.parent_id
            FROM auction.categories c JOIN ancestors a ON c.id = a.parent_id
        )
        SELECT 1 FROM ancestors WHERE id = NEW.id
    ) THEN
        RAISE EXCEPTION 'Cây danh mục không được có chu trình' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER category_tree_guard
    BEFORE INSERT OR UPDATE ON auction.categories
    FOR EACH ROW EXECUTE FUNCTION auction.guard_category_tree();

-- ---------------------------------------------------------------------
-- 5. CHUYÊN BIỆT HÓA TOÀN PHẦN + PHÂN LY (total, disjoint)
-- ---------------------------------------------------------------------
-- FK con -> cha chỉ bảo đảm "lớp con có cha". Muốn "mỗi tài sản có ĐÚNG MỘT
-- lớp con khớp kind" phải kiểm tra cả 4 bảng; kiểm tra lúc COMMIT (DEFERRED)
-- để cho phép chèn cha trước, con sau trong cùng giao dịch.
CREATE OR REPLACE FUNCTION auction.guard_asset_subtype() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, auction, pg_temp AS $$
DECLARE
    v_asset_ids   bigint[];
    v_asset_id    bigint;
    v_kind        text;
    v_artworks    integer;
    v_collectible integer;
    v_electronic  integer;
BEGIN
    -- UPDATE có thể chuyển lớp con sang tài sản khác: kiểm tra cả cũ lẫn mới.
    IF TG_TABLE_NAME = 'assets' THEN
        v_asset_ids := ARRAY[NEW.id, OLD.id];
    ELSE
        v_asset_ids := ARRAY[NEW.asset_id, OLD.asset_id];
    END IF;

    FOR v_asset_id IN SELECT DISTINCT unnest(v_asset_ids) LOOP
        SELECT kind INTO v_kind FROM auction.assets WHERE id = v_asset_id;
        IF NOT FOUND THEN
            CONTINUE;                         -- tài sản đã bị xóa cùng các lớp con
        END IF;
        SELECT count(*) INTO v_artworks    FROM auction.artworks     WHERE asset_id = v_asset_id;
        SELECT count(*) INTO v_collectible FROM auction.collectibles WHERE asset_id = v_asset_id;
        SELECT count(*) INTO v_electronic  FROM auction.electronics  WHERE asset_id = v_asset_id;

        IF v_artworks + v_collectible + v_electronic <> 1
           OR (v_kind = 'ARTWORK'     AND v_artworks    <> 1)
           OR (v_kind = 'COLLECTIBLE' AND v_collectible <> 1)
           OR (v_kind = 'ELECTRONIC'  AND v_electronic  <> 1) THEN
            RAISE EXCEPTION 'Tài sản % phải thuộc đúng một lớp con khớp kind', v_asset_id
                USING ERRCODE = '23514';
        END IF;
    END LOOP;
    RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS asset_subtype_guard ON auction.assets;
CREATE CONSTRAINT TRIGGER asset_subtype_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.assets
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS artwork_subtype_guard ON auction.artworks;
CREATE CONSTRAINT TRIGGER artwork_subtype_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.artworks
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS collectible_subtype_guard ON auction.collectibles;
CREATE CONSTRAINT TRIGGER collectible_subtype_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.collectibles
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS electronic_subtype_guard ON auction.electronics;
CREATE CONSTRAINT TRIGGER electronic_subtype_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.electronics
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();

-- ---------------------------------------------------------------------
-- 6. LỊCH SỬ BẤT BIẾN
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION auction.reject_history_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    RAISE EXCEPTION 'Lịch sử và kết quả đã ghi là bất biến' USING ERRCODE = '23514';
END $$;
CREATE OR REPLACE TRIGGER bids_immutable BEFORE UPDATE OR DELETE ON auction.bids
    FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();
CREATE OR REPLACE TRIGGER results_immutable BEFORE UPDATE OR DELETE ON auction.results
    FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();
CREATE OR REPLACE TRIGGER audit_immutable BEFORE UPDATE OR DELETE ON auction.audit_log
    FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();

-- ---------------------------------------------------------------------
-- 7. GIÁ HIỆN TẠI VÀ KẾT QUẢ LUÔN KHỚP LỊCH SỬ (kiểm tra lúc COMMIT)
-- ---------------------------------------------------------------------
-- Bất biến kiểm tra cho phiên bị chạm tới:
--   (a) current_price = MAX(bids.amount), leading_bid_id = lượt đó (NULL nếu rỗng)
--   (b) CLOSED <=> có đúng một kết quả, và lượt thắng = lượt dẫn đầu
-- Nếu sai, COMMIT bị hủy => không bao giờ lưu được trạng thái mâu thuẫn.
CREATE OR REPLACE FUNCTION auction.guard_auction_consistency() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, auction, pg_temp AS $$
DECLARE
    v_auction_id bigint;
    v_auction    auction.auctions%ROWTYPE;
    v_top_bid    auction.bids%ROWTYPE;
    v_result     auction.results%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME = 'auctions' THEN
        v_auction_id := COALESCE(NEW.id, OLD.id);
    ELSE
        v_auction_id := COALESCE(NEW.auction_id, OLD.auction_id);
    END IF;

    SELECT * INTO v_auction FROM auction.auctions WHERE id = v_auction_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    -- (a) cache khớp lượt cao nhất
    SELECT * INTO v_top_bid FROM auction.bids
    WHERE auction_id = v_auction_id
    ORDER BY amount DESC, id DESC
    LIMIT 1;
    IF v_auction.current_price  IS DISTINCT FROM v_top_bid.amount
       OR v_auction.leading_bid_id IS DISTINCT FROM v_top_bid.id THEN
        RAISE EXCEPTION 'Giá cache/người dẫn đầu phiên % không khớp lịch sử', v_auction_id
            USING ERRCODE = '23514';
    END IF;

    -- (b) trạng thái khớp kết quả
    SELECT * INTO v_result FROM auction.results WHERE auction_id = v_auction_id;
    IF (v_auction.status = 'CLOSED' AND (NOT FOUND OR v_result.winning_bid_id IS DISTINCT FROM v_top_bid.id))
       OR (v_auction.status = 'OPEN' AND FOUND) THEN
        RAISE EXCEPTION 'Kết quả phiên % không khớp trạng thái/lượt cao nhất', v_auction_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS auction_consistency_guard ON auction.auctions;
CREATE CONSTRAINT TRIGGER auction_consistency_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.auctions
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();
DROP TRIGGER IF EXISTS bid_consistency_guard ON auction.bids;
CREATE CONSTRAINT TRIGGER bid_consistency_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.bids
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();
DROP TRIGGER IF EXISTS result_consistency_guard ON auction.results;
CREATE CONSTRAINT TRIGGER result_consistency_guard
    AFTER INSERT OR UPDATE OR DELETE ON auction.results
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();

COMMENT ON COLUMN auction.auctions.current_price IS
    'Cache max(bids.amount), NULL nếu chưa có bid; cập nhật cùng transaction và kiểm tra deferred.';
COMMENT ON COLUMN auction.bids.request_id IS
    'UUID idempotency toàn hệ thống; chỉ lượt chấp nhận mới được lưu.';
COMMENT ON CONSTRAINT bids_auction_id_amount_key ON auction.bids IS
    'Khóa ứng viên (auction_id, amount): hai yêu cầu cùng mức giá trong một phiên chỉ một được ghi.';
COMMENT ON INDEX auction.auctions_one_open_per_asset IS
    'Một tài sản không thể nằm trong hai phiên đang mở cùng lúc.';
COMMENT ON TABLE auction.results IS
    'Một hàng mỗi phiên CLOSED, winning_bid_id NULL nếu không có người thắng; giá thắng suy ra từ bids.';
COMMIT;
