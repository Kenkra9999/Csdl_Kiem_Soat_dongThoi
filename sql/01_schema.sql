-- Bài 19. Chạy trong CSDL riêng của đồ án; không xóa CSDL/schema có sẵn.
BEGIN;
CREATE SCHEMA IF NOT EXISTS auction;

CREATE TABLE IF NOT EXISTS auction.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    email text NOT NULL UNIQUE CHECK (email = lower(email) AND position('@' in email) > 1),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS auction.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES auction.categories(id),
    name text NOT NULL CHECK (btrim(name) <> ''),
    CHECK (parent_id IS DISTINCT FROM id),
    UNIQUE NULLS NOT DISTINCT (parent_id, name)
);
CREATE TABLE IF NOT EXISTS auction.assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id bigint NOT NULL REFERENCES auction.users(id),
    category_id bigint NOT NULL REFERENCES auction.categories(id),
    kind text NOT NULL CHECK (kind IN ('ARTWORK','COLLECTIBLE','ELECTRONIC')),
    title text NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS auction.artworks (
    asset_id bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    artist text NOT NULL, material text NOT NULL,
    creation_year integer CHECK (creation_year BETWEEN 1 AND 9999)
);
CREATE TABLE IF NOT EXISTS auction.collectibles (
    asset_id bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    origin text NOT NULL, rarity text NOT NULL,
    production_year integer CHECK (production_year BETWEEN 1 AND 9999)
);
CREATE TABLE IF NOT EXISTS auction.electronics (
    asset_id bigint PRIMARY KEY REFERENCES auction.assets(id) ON DELETE CASCADE,
    brand text NOT NULL, model text NOT NULL,
    serial_number text UNIQUE, condition text NOT NULL
);
CREATE TABLE IF NOT EXISTS auction.auctions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id bigint NOT NULL REFERENCES auction.assets(id),
    start_price numeric(18,2) NOT NULL CHECK (start_price > 0 AND start_price <> 'NaN'::numeric),
    bid_step numeric(18,2) NOT NULL CHECK (bid_step > 0 AND bid_step <> 'NaN'::numeric),
    opens_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
    current_price numeric(18,2),
    leading_bid_id bigint,
    revision bigint NOT NULL DEFAULT 0,
    CHECK (closes_at > opens_at),
    CHECK ((current_price IS NULL) = (leading_bid_id IS NULL)),
    CHECK (current_price IS NULL OR (current_price >= start_price AND current_price <> 'NaN'::numeric))
);
CREATE TABLE IF NOT EXISTS auction.registrations (
    auction_id bigint NOT NULL REFERENCES auction.auctions(id),
    user_id bigint NOT NULL REFERENCES auction.users(id),
    status text NOT NULL DEFAULT 'APPROVED' CHECK (status IN ('APPROVED','REVOKED')),
    registered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (auction_id,user_id)
);
CREATE TABLE IF NOT EXISTS auction.bids (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id bigint NOT NULL,
    bidder_id bigint NOT NULL,
    amount numeric(18,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    request_id uuid NOT NULL UNIQUE,
    accepted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (auction_id,bidder_id) REFERENCES auction.registrations(auction_id,user_id),
    UNIQUE (id,auction_id)
);
-- Khóa ngoại kép chứng minh lượt dẫn đầu thuộc đúng phiên.
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='auctions_leading_bid_fk' AND conrelid='auction.auctions'::regclass) THEN
        ALTER TABLE auction.auctions ADD CONSTRAINT auctions_leading_bid_fk
        FOREIGN KEY (leading_bid_id,id) REFERENCES auction.bids(id,auction_id)
        DEFERRABLE INITIALLY DEFERRED;
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS auction.results (
    auction_id bigint PRIMARY KEY REFERENCES auction.auctions(id),
    winning_bid_id bigint,
    closed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (winning_bid_id,auction_id) REFERENCES auction.bids(id,auction_id)
);
CREATE TABLE IF NOT EXISTS auction.audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id bigint NOT NULL REFERENCES auction.auctions(id),
    action text NOT NULL CHECK (action IN ('BID_ACCEPTED','AUCTION_CLOSED')),
    actor_id bigint REFERENCES auction.users(id),
    details jsonb NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    transaction_id bigint NOT NULL DEFAULT txid_current()
);
CREATE INDEX IF NOT EXISTS auctions_open_deadline_idx ON auction.auctions(closes_at) WHERE status='OPEN';
CREATE INDEX IF NOT EXISTS assets_category_idx ON auction.assets(category_id);
CREATE INDEX IF NOT EXISTS categories_parent_idx ON auction.categories(parent_id);
CREATE INDEX IF NOT EXISTS bids_auction_price_idx ON auction.bids(auction_id,amount DESC,id DESC);
CREATE INDEX IF NOT EXISTS bids_bidder_idx ON auction.bids(bidder_id);
CREATE INDEX IF NOT EXISTS audit_auction_idx ON auction.audit_log(auction_id,occurred_at);

CREATE OR REPLACE FUNCTION auction.guard_category_tree() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,auction AS $$
BEGIN
    -- Chỉ dữ liệu quản trị; tuần tự hóa chỉnh sửa cây để ngăn chu trình write skew.
    -- REPEATABLE READ giữ snapshot trước lúc chờ advisory lock nhưng không có SSI;
    -- vì vậy không được dùng mức này để sửa cây. SERIALIZABLE có SSI + retry.
    IF current_setting('transaction_isolation')='repeatable read' THEN
        RAISE EXCEPTION 'Sửa cây danh mục dùng READ COMMITTED hoặc SERIALIZABLE có retry'
            USING ERRCODE='25001';
    END IF;
    PERFORM pg_advisory_xact_lock(190019,1);
    IF NEW.parent_id IS NOT NULL AND EXISTS (
        WITH RECURSIVE ancestors(id,parent_id) AS (
            SELECT id,parent_id FROM auction.categories WHERE id=NEW.parent_id
            UNION
            SELECT c.id,c.parent_id FROM auction.categories c JOIN ancestors a ON c.id=a.parent_id
        ) SELECT 1 FROM ancestors WHERE id=NEW.id
    ) THEN RAISE EXCEPTION 'Cây danh mục không được có chu trình' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER category_tree_guard BEFORE INSERT OR UPDATE ON auction.categories
FOR EACH ROW EXECUTE FUNCTION auction.guard_category_tree();

CREATE OR REPLACE FUNCTION auction.guard_asset_subtype() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,auction AS $$
DECLARE v_id bigint; v_ids bigint[]; v_kind text; v_art integer; v_col integer; v_ele integer;
BEGIN
    IF TG_TABLE_NAME='assets' THEN v_ids:=ARRAY[NEW.id,OLD.id];
    ELSE v_ids:=ARRAY[NEW.asset_id,OLD.asset_id]; END IF;
    -- UPDATE khóa lớp con phải kiểm tra cả tài sản cũ lẫn tài sản mới.
    FOR v_id IN SELECT DISTINCT unnest(v_ids) LOOP
        SELECT kind INTO v_kind FROM auction.assets WHERE id=v_id;
        IF NOT FOUND THEN CONTINUE; END IF;
        SELECT count(*) INTO v_art FROM auction.artworks WHERE asset_id=v_id;
        SELECT count(*) INTO v_col FROM auction.collectibles WHERE asset_id=v_id;
        SELECT count(*) INTO v_ele FROM auction.electronics WHERE asset_id=v_id;
        IF v_art+v_col+v_ele<>1 OR (v_kind='ARTWORK' AND v_art<>1)
           OR (v_kind='COLLECTIBLE' AND v_col<>1) OR (v_kind='ELECTRONIC' AND v_ele<>1) THEN
            RAISE EXCEPTION 'Tài sản % phải thuộc đúng một lớp con khớp kind',v_id USING ERRCODE='23514';
        END IF;
    END LOOP;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS asset_subtype_guard ON auction.assets;
CREATE CONSTRAINT TRIGGER asset_subtype_guard AFTER INSERT OR UPDATE OR DELETE ON auction.assets
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS artwork_subtype_guard ON auction.artworks;
CREATE CONSTRAINT TRIGGER artwork_subtype_guard AFTER INSERT OR UPDATE OR DELETE ON auction.artworks
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS collectible_subtype_guard ON auction.collectibles;
CREATE CONSTRAINT TRIGGER collectible_subtype_guard AFTER INSERT OR UPDATE OR DELETE ON auction.collectibles
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();
DROP TRIGGER IF EXISTS electronic_subtype_guard ON auction.electronics;
CREATE CONSTRAINT TRIGGER electronic_subtype_guard AFTER INSERT OR UPDATE OR DELETE ON auction.electronics
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_asset_subtype();

CREATE OR REPLACE FUNCTION auction.reject_history_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$ BEGIN
    RAISE EXCEPTION 'Lịch sử và kết quả đã ghi là bất biến' USING ERRCODE='23514';
END $$;
CREATE OR REPLACE TRIGGER bids_immutable BEFORE UPDATE OR DELETE ON auction.bids
FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();
CREATE OR REPLACE TRIGGER results_immutable BEFORE UPDATE OR DELETE ON auction.results
FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();
CREATE OR REPLACE TRIGGER audit_immutable BEFORE UPDATE OR DELETE ON auction.audit_log
FOR EACH ROW EXECUTE FUNCTION auction.reject_history_mutation();

CREATE OR REPLACE FUNCTION auction.guard_auction_consistency() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,auction AS $$
DECLARE v_id bigint; v_a auction.auctions%ROWTYPE; v_b auction.bids%ROWTYPE; v_r auction.results%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME='auctions' THEN v_id:=COALESCE(NEW.id,OLD.id);
    ELSE v_id:=COALESCE(NEW.auction_id,OLD.auction_id); END IF;
    SELECT * INTO v_a FROM auction.auctions WHERE id=v_id;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT * INTO v_b FROM auction.bids WHERE auction_id=v_id ORDER BY amount DESC,id DESC LIMIT 1;
    IF v_a.current_price IS DISTINCT FROM v_b.amount OR v_a.leading_bid_id IS DISTINCT FROM v_b.id THEN
        RAISE EXCEPTION 'Giá cache/người dẫn đầu phiên % không khớp lịch sử',v_id USING ERRCODE='23514';
    END IF;
    SELECT * INTO v_r FROM auction.results WHERE auction_id=v_id;
    IF (v_a.status='CLOSED' AND (NOT FOUND OR v_r.winning_bid_id IS DISTINCT FROM v_b.id))
       OR (v_a.status='OPEN' AND FOUND) THEN
        RAISE EXCEPTION 'Kết quả phiên % không khớp trạng thái/lượt cao nhất',v_id USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS auction_consistency_guard ON auction.auctions;
CREATE CONSTRAINT TRIGGER auction_consistency_guard AFTER INSERT OR UPDATE OR DELETE ON auction.auctions
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();
DROP TRIGGER IF EXISTS bid_consistency_guard ON auction.bids;
CREATE CONSTRAINT TRIGGER bid_consistency_guard AFTER INSERT OR UPDATE OR DELETE ON auction.bids
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();
DROP TRIGGER IF EXISTS result_consistency_guard ON auction.results;
CREATE CONSTRAINT TRIGGER result_consistency_guard AFTER INSERT OR UPDATE OR DELETE ON auction.results
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION auction.guard_auction_consistency();

COMMENT ON COLUMN auction.auctions.current_price IS 'Cache max(bids.amount), NULL nếu chưa có bid; cập nhật cùng transaction và kiểm tra deferred.';
COMMENT ON COLUMN auction.bids.request_id IS 'UUID idempotency toàn hệ thống; chỉ lượt chấp nhận mới được lưu.';
COMMENT ON TABLE auction.results IS 'Một hàng mỗi phiên CLOSED, winning_bid_id NULL nếu không có người thắng; giá thắng suy ra từ bids.';
COMMIT;
